using System.Collections.Generic;
using System.Text;

namespace VoyageForge.Rpc.CodeGen
{
    /// <summary>把 RPC 方法参数生成为请求 DTO 的 C# 源码。</summary>
    /// <remarks>
    /// <para>移植自试验包 Rpc.CodeGen.Probe。</para>
    /// <para>
    /// <b>DTO 必须 <c>partial</c></b>：MemoryPack 的 <c>TypeMeta.Emit()</c> 发射的是
    /// <c>partial class X : IMemoryPackable&lt;X&gt;</c>，也就是"原类型的一个部分"，
    /// 而不是独立 Formatter 类。少写 partial 会导致两份声明无法合并。
    /// </para>
    /// <para>
    /// <b>参数按名称序数排序</b>：调用方与被调用方是<b>各自程序集</b>分别生成的，
    /// 两边的参数顺序必须由同一个确定性规则导出，否则 <c>MemoryPackOrder</c> 会错位。
    /// </para>
    /// <para>
    /// <b>显式写 <c>[MemoryPackOrder]</c></b>：让序列化布局在生成代码里一眼可见，
    /// 而不是依赖"成员声明顺序"这种隐式约定。
    /// </para>
    /// </remarks>
    public static class RpcDtoSourceBuilder
    {
        /// <summary>为方法参数生成 DTO 源码。</summary>
        /// <param name="dtoNamespace">DTO 命名空间。</param>
        /// <param name="dtoName">DTO 简单类名。</param>
        /// <param name="controllerName">控制器名（写进注释便于溯源）。</param>
        /// <param name="methodName">方法名（写进注释便于溯源）。</param>
        /// <param name="parameters">已按名称排序的参数。</param>
        public static string Emit(
            string dtoNamespace,
            string dtoName,
            string controllerName,
            string methodName,
            IReadOnlyList<RpcDtoParameter> parameters)
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("// 由 VoyageForge Rpc.Generator 生成：RPC 方法参数 DTO。");
            builder.AppendLine("// 这个文件同时是 MemoryPack 序列化实现的一半（另一半由 MemoryPack Emitter 发射）。");
            builder.AppendLine("#nullable enable");
            builder.AppendLine();
            builder.AppendLine("namespace " + dtoNamespace);
            builder.AppendLine("{");
            builder.AppendLine("    /// <summary>");
            builder.AppendLine("    /// 由控制器 <c>" + Escape(controllerName) + "</c> 的方法 <c>" + Escape(methodName) + "</c> 的参数自动生成。");
            builder.AppendLine("    /// </summary>");
            builder.AppendLine("    /// <remarks>");
            builder.AppendLine("    /// 参数按名称序数排序后落成属性，保证调用方与被调用方各自生成时布局完全一致。");
            builder.AppendLine("    /// 必须保持 partial：MemoryPack 的序列化实现是本类的另一个 partial 部分。");
            builder.AppendLine("    /// </remarks>");
            builder.AppendLine("    [global::MemoryPack.MemoryPackable]");
            builder.AppendLine("    public partial class " + dtoName);
            builder.AppendLine("    {");
            builder.AppendLine("        /// <summary>无参构造：MemoryPack 反序列化时用它创建实例。</summary>");
            builder.AppendLine("        public " + dtoName + "()");
            builder.AppendLine("        {");
            builder.AppendLine("        }");

            for (var index = 0; index < parameters.Count; index++)
            {
                var parameter = parameters[index];
                builder.AppendLine();
                builder.AppendLine("        /// <summary>对应契约参数 <c>" + Escape(parameter.ParameterName) + "</c>。</summary>");
                builder.AppendLine("        [global::MemoryPack.MemoryPackOrder(" + index + ")]");

                // 引用类型补 default!，避免宿主工程因 CS8618（非可空属性未初始化）刷警告。
                var initializer = parameter.IsReferenceType ? " = default!;" : string.Empty;
                builder.AppendLine("        public " + parameter.TypeDisplay + " " + parameter.PropertyName + " { get; set; }" + initializer);
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");

            return SourceTextNormalizer.ToUnixLineEndings(builder.ToString());
        }

        /// <summary>转义写进 XML 文档注释的文本。</summary>
        private static string Escape(string text)
        {
            return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }
    }
}
