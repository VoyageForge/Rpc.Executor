using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace VoyageForge.Rpc.CodeGen
{
    public sealed partial class RpcPartialEmitter
    {
        private const string Binding = "VoyageForge.Rpc.Transport.RpcControllerBindingAttribute";
        internal static SyntaxTree? Emit(GeneratorExecutionContext context, TypeDeclarationSyntax node)
        {
            var model = context.Compilation.GetSemanticModel(node.SyntaxTree);
            if (!(model.GetDeclaredSymbol(node, context.CancellationToken) is INamedTypeSymbol owner)) return null;
            var anchor = owner.GetAttributes().FirstOrDefault(a => IsOwnerAttribute(a.AttributeClass?.ToDisplayString()))
                ?.ApplicationSyntaxReference;
            if (anchor == null || anchor.SyntaxTree != node.SyntaxTree || !node.Span.Contains(anchor.Span)) return null;

            var emitter = new RpcPartialEmitter(owner, model, node.CloseBraceToken.SpanStart);
            string members = emitter.Generate();
            if (members.Length == 0) return null;
            string kind = owner.TypeKind == TypeKind.Interface ? "interface" : "class";
            string declaration = $"partial {kind} {Id(owner.Name)} {{ {members} }}";
            // Preserve using/alias scopes for the same readable type names as the handwritten declaration.
            MemberDeclarationSyntax part = SyntaxFactory.ParseMemberDeclaration(declaration)!;
            foreach (var ns in node.Ancestors().OfType<BaseNamespaceDeclarationSyntax>())
                part = SyntaxFactory.NamespaceDeclaration(ns.Name.WithoutTrivia())
                    .WithUsings(ns.Usings).WithExterns(ns.Externs).AddMembers(part);
            var original = node.SyntaxTree.GetCompilationUnitRoot(context.CancellationToken);
            var unit = SyntaxFactory.CompilationUnit().WithExterns(original.Externs).WithUsings(original.Usings).AddMembers(part);
            string hint = owner.ToDisplayString() + ".Rpc.g.cs";
            var source = SourceText.From("// <auto-generated/>\n" + unit.NormalizeWhitespace(eol: "\n").ToFullString(), Encoding.UTF8);
            context.AddSource(hint, source);
            return CSharpSyntaxTree.ParseText(source, (CSharpParseOptions)context.ParseOptions, hint,
                cancellationToken: context.CancellationToken);
        }

        private static bool IsOwnerAttribute(string name) =>
            name == ContractAttr || name == RpcControllerAttr || name == SessionAttr || name == ApiAttr || name == Binding;

        private readonly INamedTypeSymbol owner;
        private readonly SemanticModel model;
        private readonly int position;
        private readonly StringBuilder code = new StringBuilder();

        private RpcPartialEmitter(INamedTypeSymbol owner, SemanticModel model, int position)
        { this.owner = owner; this.model = model; this.position = position; }

        private string Type(ITypeSymbol symbol) => symbol.ToMinimalDisplayString(model, position);
        private void Line(string line) => code.AppendLine(line);
        private void Require(bool ok, string message)
        { if (!ok) throw new InvalidOperationException(owner + ": " + message); }

        private string Generate()
        {
            Require(owner.ContainingType == null && !owner.IsGenericType && IsPartial(owner), "RPC 声明必须是顶层非泛型 partial 类型。");
            if (Attribute(owner, ContractAttr) != null) EmitContract();
            else if (Attribute(owner, RpcControllerAttr) != null) EmitController();
            else EmitSession();
            return code.ToString();
        }

        private sealed class Call
        {
            public IMethodSymbol Method;
            public List<IParameterSymbol> Args;
            public IParameterSymbol Token;
            public ITypeSymbol Result;
            public string WireName, Dto, Dispatch;
            public ulong Number;
            public string Literal => "0x" + Number.ToString("X16") + "UL";
        }

        private List<Call> Calls(INamedTypeSymbol type, bool inbound)
        {
            var attr = Attribute(type, inbound ? RpcControllerAttr : ContractAttr);
            string name = attr?.ConstructorArguments.FirstOrDefault().Value as string;
            if (string.IsNullOrWhiteSpace(name))
                name = inbound ? Regex.Replace(type.Name, "Controller$", "") : ControllerName(type);
            var methods = inbound ? type.GetMembers().OfType<IMethodSymbol>().Where(m => Attribute(m, RpcMethodAttr) != null) : Methods(type);
            var calls = new List<Call>();
            foreach (var method in methods.OrderBy(MethodIdentity, StringComparer.Ordinal))
            {
                Require(method.DeclaredAccessibility == Accessibility.Public, method.Name + " must be public.");
                Require(ValidateMethod(method, out var args, out var token, out var result, out _, out var error), method.Name + ": " + error);
                string wire = Attribute(method, RpcMethodAttr)?.ConstructorArguments.FirstOrDefault().Value as string;
                if (string.IsNullOrWhiteSpace(wire)) wire = method.Name;
                ulong number = Hash(CanonicalKey(name, wire, args));
                Require(calls.All(c => c.Number != number), "Duplicate MethodId: " + wire);
                calls.Add(new Call { Method = method, Args = args, Token = token, Result = result, WireName = wire, Number = number });
            }
            foreach (var call in calls)
            {
                string stem = Regex.Replace(call.Method.Name, "Async$", "");
                if (calls.Count(c => Regex.Replace(c.Method.Name, "Async$", "") == stem) > 1)
                    stem += "_" + call.Number.ToString("X16");
                call.Dto = stem + "Request";
                call.Dispatch = "Dispatch" + stem + "Async";
            }
            return calls;
        }

        private void EmitContract()
        {
            Require(owner.TypeKind == TypeKind.Interface && owner.DeclaredAccessibility == Accessibility.Public, "Expected public interface.");
            Require(!owner.AllInterfaces.Concat(new[]{owner}).SelectMany(i => i.GetMembers()).Any(m => m is IPropertySymbol || m is IEventSymbol), "RPC contracts only support methods.");
            EmitDtos(Calls(owner, false), true);
        }

        private void EmitDtos(List<Call> calls, bool exposed)
        {
            foreach (var call in calls.Where(c => c.Args.Count > 0))
            {
                Line("[global::MemoryPack.MemoryPackable]");
                Line((exposed ? "public" : "private") + " sealed partial class " + call.Dto + " {");
                foreach (var arg in call.Args)
                    Line("public " + Type(arg.Type) + " " + Id(arg.Name) + " { get; set; }");
                Line("}");
            }
        }

        private const string Transport = "global::VoyageForge.Rpc.Transport.";
        private string Framework(string name) => Type(model.Compilation.GetTypeByMetadataName("VoyageForge.Rpc.Transport." + name)
            ?? throw new InvalidOperationException("Missing transport type: " + name));

        private void EmitController()
        {
            Require(Derives(owner, ControllerBase) && !owner.IsAbstract, "Expected concrete RpcControllerBase.");
            var calls = Calls(owner, true);
            EmitDtos(calls, false);
            string self = Id(owner.Name);
            string protocol = Attribute(owner, RpcControllerAttr)?.ConstructorArguments.FirstOrDefault().Value as string;
            if (string.IsNullOrWhiteSpace(protocol)) protocol = Regex.Replace(owner.Name, "Controller$", "");
            Line($"public static void RegisterRpc({Framework("RpcControllerRegistry")} registry, global::System.Func<{self}> factory) {{");
            Line("registry.Controllers.Register(factory);");
            foreach (var c in calls)
            {
                string route = "route" + c.Dispatch.Substring("Dispatch".Length);
                Line($"var {route} = new {Framework("RpcMethodDescriptor")}();");
                Line($"{route}.MethodId = {c.Literal};");
                Line($"{route}.ControllerName = {Lit(protocol)};");
                Line($"{route}.MethodName = {Lit(c.WireName)};");
                Line($"{route}.Signature = {Lit(Signature(c.Args))};");
                Line($"{route}.Handler = (session, packet, ct) => session.Local<{self}>().{c.Dispatch}(packet, ct);");
                Line($"registry.Register({route});");
            }
            Line("}");
            foreach (var c in calls)
            {
                Line($"private async global::System.Threading.Tasks.Task<byte[]> {c.Dispatch}({Transport}Request<global::System.ReadOnlyMemory<byte>> packet, global::System.Threading.CancellationToken ct) {{");
                if (c.Args.Count > 0)
                    Line($"var args = global::MemoryPack.MemoryPackSerializer.Deserialize<{c.Dto}>(packet.Data.Span);");
                var args = c.Args.Select(a => "args." + Id(a.Name)).ToList();
                if (c.Token != null) args.Add("ct");
                Line($"{(c.Result == null ? "" : "var result = ")}await this.{Id(c.Method.Name)}({string.Join(", ", args)}).ConfigureAwait(false);");
                Line(c.Result == null ? "return global::System.Array.Empty<byte>();" : "return global::MemoryPack.MemoryPackSerializer.Serialize(result);");
                Line("}");
            }
        }

        private List<INamedTypeSymbol> Bindings(string attr)
        {
            var list = owner.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == attr)
                .Select(a => a.ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol).ToList();
            Require(list.All(t => t != null && t.TypeKind != TypeKind.Error) &&
                list.Distinct(SymbolEqualityComparer.Default).Count() == list.Count, "Invalid or duplicate binding: " + attr);
            return list.Select(t => t!).ToList();
        }

        private void EmitSession()
        {
            Require(owner.BaseType?.ToDisplayString() == "VoyageForge.Rpc.Transport.Session" && !owner.IsAbstract, "Expected concrete Session subclass.");
            Require(owner.InstanceConstructors.All(c => c.IsImplicitlyDeclared) && owner.GetMembers("Create").IsEmpty, "Create and constructors are generated.");
            var contracts = Bindings(ApiAttr);
            var controllers = Bindings(Binding);
            var self = Id(owner.Name);
            var registry = Framework("RpcControllerRegistry");
            Line($"private {self}({registry} registry, int maxFrameBytes) : base(registry, maxFrameBytes) {{");
            string Proxy(INamedTypeSymbol c) => (contracts.Count(t => t.Name == c.Name) == 1 ? c.Name : SafeName(c.ToDisplayString())) + "Proxy";
            foreach (var contract in contracts)
            {
                Require(Attribute(contract, ContractAttr) != null, "Missing RpcContract: " + contract);
                Line($"RegisterRemote<{Type(contract)}>(new {Proxy(contract)}(this));");
            }
            Line("}");
            string Factory(INamedTypeSymbol c) => "create" + (controllers.Count(other => c.Name == other.Name) == 1 ? c.Name : SafeName(c.ToDisplayString()));
            var factories = controllers.Select(c => "global::System.Func<" + Type(c) + "> " + Factory(c) + " = null").ToArray();
            Line($"public static {self} Create(global::System.Net.Sockets.TcpClient socket = null, int maxFrameBytes = DefaultMaxFrameBytes" +
                (factories.Length == 0 ? "" : ", " + string.Join(", ", factories)) + ") {");
            Line($"var registry = new {registry}();");
            var routes = new HashSet<ulong>();
            for (int i = 0; i < controllers.Count; i++)
            {
                var c = controllers[i];
                Require(Attribute(c, RpcControllerAttr) != null && Derives(c, ControllerBase), "Invalid controller binding: " + c);
                foreach (var route in Calls(c,true)) Require(routes.Add(route.Number), "Duplicate route: " + route.WireName);
                bool constructible = c.InstanceConstructors.Any(k => k.Parameters.Length == 0 && model.Compilation.IsSymbolAccessibleWithin(k, owner));
                string fallback = constructible ? $"(() => new {Type(c)}())" : $"throw new global::System.ArgumentNullException(nameof({Factory(c)}))";
                Line($"{Type(c)}.RegisterRpc(registry, {Factory(c)} ?? {fallback});");
            }
            Line($"var session = new {self}(registry, maxFrameBytes);");
            Line("if (socket != null) session.Attach(socket);");
            Line("return session; }");
            foreach (var c in contracts)
            {
                Line($"private sealed class {Proxy(c)} : {Type(c)} {{");
                Line($"private readonly {self} session;");
                Line($"public {Proxy(c)}({self} session) {{ this.session = session; }}");
                foreach (var call in Calls(c, false))
                {
                    var m = call.Method;
                    string argsType = call.Args.Count == 0 ? Framework("RpcUnit") : Type(c) + "." + call.Dto;
                    string data = "default";
                    var parameters = m.Parameters.Select(p => Type(p.Type) + " " + Id(p.Name));
                    Line($"public {Type(m.ReturnType)} {Id(m.Name)}({string.Join(", ",parameters)}) {{");
                    if (call.Args.Count > 0)
                    {
                        data = "request";
                        while (m.Parameters.Any(p => p.Name == data)) data += "Data";
                        Line($"var {data} = new {argsType}();");
                        foreach (var arg in call.Args) Line($"{data}.{Id(arg.Name)} = {Id(arg.Name)};");
                    }
                    Line($"return this.session.InvokeAsync<{argsType}, {(call.Result == null ? Framework("RpcUnit") : Type(call.Result))}>({call.Literal}, {data}, {(call.Token == null ? "default" : Id(call.Token.Name))}); }}");
                }
                Line("}");
            }
        }
    }
}
