namespace VoyageForge.Rpc.CodeGen
{
    /// <summary>
    /// 把 MemoryPack <c>TypeMeta.Emit()</c> 产生的"裸类型体"包装成完整的 C# 文件。
    /// </summary>
    /// <remarks>
    /// <para>移植自试验包 Rpc.CodeGen.Probe。</para>
    /// <para>
    /// <b>为什么需要这一层</b>：<c>Emit()</c> 只输出
    /// <c>partial class X : IMemoryPackable&lt;X&gt; { ... }</c> 这一段，既不带 using 也不带 namespace。
    /// 文件头、namespace、<c>using MemoryPack;</c> 都要在这里补齐。
    /// </para>
    /// <para>
    /// <b>为什么必须带 <c>using MemoryPack;</c></b>：发射代码大部分成员写的是
    /// <c>global::MemoryPack.XXX</c> 全名，但嵌套 formatter 声明写的是裸
    /// <c>MemoryPackFormatter&lt;T&gt;</c>。少了这条 using 会 CS0246。
    /// </para>
    /// <para>namespace 用块式（C# 9 不支持文件级 namespace）。</para>
    /// </remarks>
    public static class RpcDtoFormatterFileBuilder
    {
        /// <summary>包装成完整源码文件。</summary>
        /// <param name="emittedBody">MemoryPack <c>Emit()</c> 输出的类型体。</param>
        /// <param name="namespaceName">类型所在的命名空间（与 DTO 相同）。</param>
        public static string Emit(string emittedBody, string namespaceName)
        {
            var source = $@"// <auto-generated/>
// 由 VoyageForge Rpc.Generator 复用 MemoryPack Emitter 生成。
// 不要手改：这段代码的形态由 MemoryPack.Generator 1.21.4 决定。
#nullable enable
#pragma warning disable CS0108 // 隐藏继承成员
#pragma warning disable CS0162 // 不可达代码
#pragma warning disable CS0164 // 标签未引用
#pragma warning disable CS0219 // 变量已赋值但未使用
#pragma warning disable CS0618 // 过时成员
#pragma warning disable CS8600 // 将 null 字面量或可能为 null 的值转换为非可空类型
#pragma warning disable CS8601 // 可能的 null 引用赋值
#pragma warning disable CS8602 // 解引用可能为 null 的引用
#pragma warning disable CS8604 // 可能的 null 引用实参
#pragma warning disable CS8619 // 值中的 null 性不匹配
#pragma warning disable CS8620 // 实参的 null 性不匹配
#pragma warning disable CS8631 // 类型不能用作类型参数
#pragma warning disable CS8765 // 参数 null 性与重写成员不匹配
#pragma warning disable CA1050 // 在命名空间中声明类型

using System;
using MemoryPack;

namespace {namespaceName}
{{
{emittedBody}
}}
";

            // 统一成 LF：Emit 的类型体来自 MemoryPack 的原始字符串字面量，行尾会跟随它自己的源文件，
            // 不规范化的话不同环境可能产出字节级不同的结果。
            return SourceTextNormalizer.ToUnixLineEndings(source);
        }
    }
}
