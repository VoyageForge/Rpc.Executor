using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace VoyageForge.Rpc.Executor.CodeGen
{
    /// <summary>
    /// 为 [RpcMessage] 类型生成 MessageId 常量与查表方法。
    /// 显式 [RpcMessage(1001)] 优先；未标注类型从 1000 开始自动编号（按类型全名排序，保证稳定）。
    /// </summary>
    [Generator]
    public sealed class RpcMessageTypeIdGenerator : ISourceGenerator
    {
        private const string AttributeFullName = "VoyageForge.Rpc.Transport.RpcMessageAttribute";
        private const ushort AutoStart = 1000;

        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new Receiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxContextReceiver is Receiver receiver) || receiver.Types.Count == 0)
            {
                return;
            }

            var entries = new List<(INamedTypeSymbol Type, ushort? Explicit)>();
            foreach (INamedTypeSymbol type in receiver.Types)
            {
                ushort? explicitId = null;
                foreach (AttributeData attribute in type.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() != AttributeFullName) continue;
                    if (attribute.ConstructorArguments.Length == 1 &&
                        attribute.ConstructorArguments[0].Value is ushort id)
                    {
                        explicitId = id;
                    }
                }

                entries.Add((type, explicitId));
            }

            // 显式编号直接采用；未标注类型按全名排序后顺序分配，保证编译稳定。
            var used = new HashSet<ushort>(entries.Where(e => e.Explicit.HasValue).Select(e => e.Explicit.Value));
            int autoIndex = AutoStart;
            var final = new List<(INamedTypeSymbol Type, ushort Id)>();
            foreach (var entry in entries.OrderBy(e => e.Type.ToDisplayString()))
            {
                if (entry.Explicit.HasValue)
                {
                    final.Add((entry.Type, entry.Explicit.Value));
                    continue;
                }

                while (used.Contains((ushort)autoIndex)) autoIndex++;
                ushort assigned = (ushort)autoIndex;
                used.Add(assigned);
                final.Add((entry.Type, assigned));
            }

            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using System;");
            source.AppendLine("using VoyageForge.Rpc.Transport;");
            source.AppendLine("namespace VoyageForge.Rpc.Transport");
            source.AppendLine("{");
            source.AppendLine("    /// <summary>源生成器分配的消息 MessageId。</summary>");
            source.AppendLine("    public static class RpcMessageIds");
            source.AppendLine("    {");
            foreach (var item in final)
            {
                source.AppendLine("        /// <summary>" + item.Type.ToDisplayString() + "</summary>");
                source.AppendLine("        public static readonly MessageId " + item.Type.Name + " = new MessageId(" + item.Id + ");");
            }

            source.AppendLine("    }");
            source.AppendLine();
            source.AppendLine("    /// <summary>源生成器分配的消息类型映射。</summary>");
            source.AppendLine("    public static class RpcMessageTypeMap");
            source.AppendLine("    {");
            source.AppendLine("        /// <summary>按类型查 MessageId。</summary>");
            source.AppendLine("        public static bool TryGetMessageId(Type type, out MessageId messageId)");
            source.AppendLine("        {");
            foreach (var item in final)
            {
                source.AppendLine("            if (type == typeof(" + item.Type.ToDisplayString() + ")) { messageId = RpcMessageIds." + item.Type.Name + "; return true; }");
            }

            source.AppendLine("            messageId = default(MessageId);");
            source.AppendLine("            return false;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        /// <summary>按 MessageId 查类型。</summary>");
            source.AppendLine("        public static bool TryGetType(MessageId messageId, out Type type)");
            source.AppendLine("        {");
            foreach (var item in final)
            {
                source.AppendLine("            if (messageId == RpcMessageIds." + item.Type.Name + ") { type = typeof(" + item.Type.ToDisplayString() + "); return true; }");
            }

            source.AppendLine("            type = null;");
            source.AppendLine("            return false;");
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine("}");

            context.AddSource("RpcMessageIds.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }

        /// <summary>收集带 [RpcMessage] 的类型。</summary>
        private sealed class Receiver : ISyntaxContextReceiver
        {
            public List<INamedTypeSymbol> Types { get; } = new List<INamedTypeSymbol>();

            public void OnVisitSyntaxNode(GeneratorSyntaxContext context)
            {
                if (!(context.Node is TypeDeclarationSyntax declaration)) return;
                if (!(context.SemanticModel.GetDeclaredSymbol(declaration) is INamedTypeSymbol symbol)) return;
                foreach (AttributeData attribute in symbol.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() == AttributeFullName)
                    {
                        Types.Add(symbol);
                        return;
                    }
                }
            }
        }
    }
}
