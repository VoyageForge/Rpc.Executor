using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using MemoryPack.Generator;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace VoyageForge.Rpc.CodeGen
{
    [Generator]
    public sealed class ControllerRpcGenerator : ISourceGenerator
    {
        private static readonly DiagnosticDescriptor InvalidDeclaration = new DiagnosticDescriptor(
            "RPC100", "RPC declaration is invalid", "{0}", "VoyageForge.RPC", DiagnosticSeverity.Error, true);

        private sealed class Receiver : ISyntaxReceiver
        {
            public readonly List<TypeDeclarationSyntax> Candidates = new List<TypeDeclarationSyntax>();

            public void OnVisitSyntaxNode(SyntaxNode node)
            {
                if (node is TypeDeclarationSyntax type && type.AttributeLists.Count != 0)
                    Candidates.Add(type);
            }
        }

        public void Initialize(GeneratorInitializationContext context) =>
            context.RegisterForSyntaxNotifications(() => new Receiver());

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxReceiver is Receiver receiver) ||
                context.Compilation.GetTypeByMetadataName("VoyageForge.Rpc.Transport.RpcControllerBindingAttribute") == null)
                return;

            var parts = new List<(SyntaxTree Tree, Location Origin)>();
            foreach (var candidate in receiver.Candidates)
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                try
                {
                    var tree = RpcPartialEmitter.Emit(context, candidate);
                    if (tree != null) parts.Add((tree, candidate.Identifier.GetLocation()));
                }
                catch (InvalidOperationException error)
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidDeclaration, candidate.Identifier.GetLocation(), error.Message));
                }
            }

            // Peer source generators receive the original compilation. Bind the generated DTOs in memory.
            if (parts.Count == 0) return;
            var compilation = context.Compilation.AddSyntaxTrees(parts.Select(part => part.Tree));
            ReferenceSymbols? references = null;
            foreach (var part in parts)
            {
                foreach (var dto in part.Tree.GetRoot(context.CancellationToken).DescendantNodes()
                    .OfType<ClassDeclarationSyntax>().Where(type => type.AttributeLists.SelectMany(list => list.Attributes)
                        .Any(attribute => attribute.Name.ToString() == "global::MemoryPack.MemoryPackable")))
                {
                    try
                    {
                        references ??= new ReferenceSymbols(compilation);
                        var symbol = compilation.GetSemanticModel(part.Tree).GetDeclaredSymbol(dto, context.CancellationToken)!;
                        EmitFormatter(context, references, symbol, dto, part.Origin);
                    }
                    catch (Exception error) when (!(error is OperationCanceledException))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(InvalidDeclaration, part.Origin, dto.Identifier + ": " + error.Message));
                    }
                }
            }
        }

        private static void EmitFormatter(GeneratorExecutionContext context, ReferenceSymbols references,
            INamedTypeSymbol symbol, ClassDeclarationSyntax dto, Location origin)
        {
            var emitter = new RpcDtoGeneratorContext(context.CancellationToken, ((CSharpParseOptions)context.ParseOptions).LanguageVersion);
            var meta = new TypeMeta(symbol, references);
            bool valid = meta.Validate(dto, emitter, unionFormatter: false);
            var body = new StringBuilder();
            if (valid) meta.Emit(body, emitter);
            foreach (var diagnostic in emitter.Diagnostics)
                context.ReportDiagnostic(Diagnostic.Create(InvalidDeclaration, origin, diagnostic.ToString()));
            if (!valid) return;

            var owner = (TypeDeclarationSyntax)dto.Parent!;
            // MemoryPack 1.21.4 emits a containing class even for interface owners.
            // Keep its DTO implementation and recreate only the outer declaration.
            var formatterTree = CSharpSyntaxTree.ParseText(body.ToString(), (CSharpParseOptions)context.ParseOptions,
                cancellationToken: context.CancellationToken);
            var wrapper = formatterTree.GetCompilationUnitRoot().Members.OfType<TypeDeclarationSyntax>().Single();
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated/>").AppendLine("#nullable enable")
                .AppendLine("#pragma warning disable CS0162, CS0164, CS0219, CS0618, CS8600, CS8601, CS8602, CS8604, CS8619, CS8620, CS8631, CS8765")
                .AppendLine("using System;").AppendLine("using MemoryPack;");
            var ns = symbol.ContainingNamespace;
            if (!ns.IsGlobalNamespace) source.Append("namespace ").Append(ns.ToDisplayString()).AppendLine(" {");
            source.Append("partial ").Append(owner.Keyword.Text).Append(' ').Append(owner.Identifier.Text)
                .AppendLine(" {").AppendLine(wrapper.Members.ToFullString()).AppendLine("}");
            if (!ns.IsGlobalNamespace) source.AppendLine("}");
            context.AddSource(symbol.ToDisplayString() + ".MemoryPack.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }
    }
}
