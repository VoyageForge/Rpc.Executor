using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace VoyageForge.Rpc.SourceGen
{
    /// <summary>生成处理器目录：一个程序集一个 RpcHandlerCatalog。</summary>
    internal static class RpcHandlerSourceWriter
    {
        private const string FileName = "VoyageForge.Rpc.Generated.RpcHandlerCatalog.g.cs";

        public static void Write(SourceProductionContext context, ImmutableArray<RpcHandlerModel> rawModels)
        {
            List<RpcHandlerModel> models = Deduplicate(context, rawModels);
            if (models.Count == 0)
            {
                return;
            }

            StringBuilder builder = new StringBuilder(4096);
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("// 由 VoyageForge.Rpc.SourceGen 生成：请求类型 → 处理器目录，请勿手改。");
            builder.AppendLine("#pragma warning disable");
            builder.AppendLine();
            builder.AppendLine("[assembly: global::VoyageForge.Rpc.Runtime.Handlers.RpcHandlerCatalogAttribute(typeof(global::VoyageForge.Rpc.Generated.RpcHandlerCatalog))]");
            builder.AppendLine();
            builder.AppendLine("namespace VoyageForge.Rpc.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    internal sealed class RpcHandlerCatalog : global::VoyageForge.Rpc.Runtime.Handlers.IRpcHandlerCatalog");
            builder.AppendLine("    {");

            for (int i = 0; i < models.Count; i++)
            {
                // 每个请求类型对应一个处理器单例（同步或异步由 isAsync 标记）
                builder.Append("        private static readonly object Handler").Append(i)
                    .Append(" = new ").Append(models[i].HandlerCodeName).AppendLine("();");
            }

            builder.AppendLine();
            builder.AppendLine("        public bool TryGet(global::System.Type requestType, out object handler, out bool isAsync)");
            builder.AppendLine("        {");

            for (int i = 0; i < models.Count; i++)
            {
                builder.Append("            // ").AppendLine(models[i].RequestCodeName);
                builder.Append("            if (requestType == typeof(").Append(models[i].RequestCodeName).AppendLine("))");
                builder.AppendLine("            {");
                builder.Append("                handler = Handler").Append(i).AppendLine(";");
                builder.Append("                isAsync = ").Append(models[i].IsAsync ? "true" : "false").AppendLine(";");
                builder.AppendLine("                return true;");
                builder.AppendLine("            }");
                builder.AppendLine();
            }

            builder.AppendLine("            handler = null;");
            builder.AppendLine("            isAsync = false;");
            builder.AppendLine("            return false;");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");

            context.AddSource(FileName, SourceText.From(builder.ToString(), Encoding.UTF8));
        }

        private static List<RpcHandlerModel> Deduplicate(SourceProductionContext context, ImmutableArray<RpcHandlerModel> rawModels)
        {
            Dictionary<string, RpcHandlerModel> byRequest = new Dictionary<string, RpcHandlerModel>(StringComparer.Ordinal);

            for (int i = 0; i < rawModels.Length; i++)
            {
                RpcHandlerModel model = rawModels[i];
                if (model == null)
                {
                    continue;
                }

                if (byRequest.ContainsKey(model.RequestCodeName))
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        Diagnostics.HandlerDuplicate,
                        model.Location,
                        model.RequestCodeName,
                        byRequest[model.RequestCodeName].HandlerCodeName,
                        model.HandlerCodeName));
                    continue;
                }

                byRequest.Add(model.RequestCodeName, model);
            }

            return new List<RpcHandlerModel>(byRequest.Values);
        }
    }
}